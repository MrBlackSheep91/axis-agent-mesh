#!/usr/bin/env tsx
/**
 * sync-twin.ts — regenerate the TypeScript mirror of axis_agent_registry
 * from the Python source-of-truth.
 *
 * Modes:
 *   (no flag)  Write packages/agent-registry/typescript/src/catalog.ts +
 *              assignments.ts AND the snapshot fixture python-pairs.json.
 *              Always succeeds; prints "synced N catalog entries, M
 *              assignments, K snapshot pairs".
 *   --check    Compare generated content against on-disk files byte-by-byte
 *              (newline-normalised). Exits 0 + "in sync" on match; exits 1
 *              with a unified diff on drift.
 *
 * Implementation notes:
 *   - The Python helper (bin/dump-python-pairs.py) is the ONLY interface
 *     to the Python source. This script never reaches into catalog.py /
 *     assignments.py directly.
 *   - We prefer /opt/homebrew/bin/python3.11 if it exists (Mac dev box
 *     has python3 -> 3.9 by default, which the package's requires-python
 *     >= 3.11 rejects). Otherwise we fall back to PATH python3.
 *   - catalog.ts uses TS camelCase field names (inPricePerM, outPricePerM,
 *     ctxTokens, supportsTools, leakRisk) — the Python source uses
 *     snake_case. The mapping is documented in the banner.
 *   - Keys are sorted alphabetically in BOTH files so diffs are stable.
 *   - The generated files MUST start with the literal banner so future
 *     code reviewers know not to edit by hand.
 */
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync, mkdirSync, statSync } from "node:fs";
import { dirname, resolve } from "node:path";

const REPO_ROOT = resolve(new URL("..", import.meta.url).pathname);

const PKG_TS_SRC = resolve(REPO_ROOT, "packages/agent-registry/typescript/src");
const PKG_TS_FIXTURES = resolve(
  REPO_ROOT,
  "packages/agent-registry/typescript/tests/snapshot-fixtures",
);

const CATALOG_OUT = resolve(PKG_TS_SRC, "catalog.ts");
const ASSIGNMENTS_OUT = resolve(PKG_TS_SRC, "assignments.ts");
const PAIRS_OUT = resolve(PKG_TS_FIXTURES, "python-pairs.json");

const BANNER = `// AUTO-GENERATED BY bin/sync-twin.ts — DO NOT EDIT`;

interface ModelSpecPython {
  id: string;
  in_price_per_m: number;
  out_price_per_m: number;
  ctx_tokens: number;
  supports_tools: boolean;
  released: string;
  family: string;
  notes: string;
  leak_risk: string;
}

interface Envelope {
  catalog: Record<string, ModelSpecPython>;
  assignments: Record<string, string>;
  pairs: Array<{
    role: string;
    env_overrides: Record<string, string>;
    expected_model_id: string;
  }>;
}

function pickPython(): string {
  const preferred = "/opt/homebrew/bin/python3.11";
  if (existsSync(preferred)) return preferred;
  return "python3";
}

function loadEnvelope(): Envelope {
  const py = pickPython();
  const out = execFileSync(py, ["bin/dump-python-pairs.py"], {
    cwd: REPO_ROOT,
    encoding: "utf8",
    stdio: ["ignore", "pipe", "inherit"],
    maxBuffer: 16 * 1024 * 1024,
  });
  return JSON.parse(out) as Envelope;
}

function escapeTsString(s: string): string {
  // JSON.stringify gives us a valid double-quoted TS string literal.
  return JSON.stringify(s);
}

function renderCatalog(catalog: Record<string, ModelSpecPython>): string {
  const lines: string[] = [];
  lines.push(BANNER);
  lines.push(`// Source: packages/agent-registry/python/axis_agent_registry/catalog.py`);
  lines.push(`// Regenerate with: npm run sync-twin`);
  lines.push(`// Drift check:    npm run sync-twin:check`);
  lines.push(`//`);
  lines.push(`// Python snake_case -> TS camelCase mapping:`);
  lines.push(`//   in_price_per_m  -> inPricePerM`);
  lines.push(`//   out_price_per_m -> outPricePerM`);
  lines.push(`//   ctx_tokens      -> ctxTokens`);
  lines.push(`//   supports_tools  -> supportsTools`);
  lines.push(`//   leak_risk       -> leakRisk`);
  lines.push("");
  lines.push("export interface ModelSpec {");
  lines.push("  id: string;");
  lines.push("  inPricePerM: number;");
  lines.push("  outPricePerM: number;");
  lines.push("  ctxTokens: number;");
  lines.push("  supportsTools: boolean;");
  lines.push("  released: string;");
  lines.push("  family: string;");
  lines.push("  notes: string;");
  lines.push("  leakRisk: string;");
  lines.push("}");
  lines.push("");
  lines.push("export const CATALOG: Record<string, ModelSpec> = {");
  const sortedIds = Object.keys(catalog).sort();
  for (const id of sortedIds) {
    const spec = catalog[id];
    lines.push(`  ${escapeTsString(id)}: {`);
    lines.push(`    id: ${escapeTsString(spec.id)},`);
    lines.push(`    inPricePerM: ${spec.in_price_per_m},`);
    lines.push(`    outPricePerM: ${spec.out_price_per_m},`);
    lines.push(`    ctxTokens: ${spec.ctx_tokens},`);
    lines.push(`    supportsTools: ${spec.supports_tools ? "true" : "false"},`);
    lines.push(`    released: ${escapeTsString(spec.released)},`);
    lines.push(`    family: ${escapeTsString(spec.family)},`);
    lines.push(`    notes: ${escapeTsString(spec.notes)},`);
    lines.push(`    leakRisk: ${escapeTsString(spec.leak_risk)},`);
    lines.push("  },");
  }
  lines.push("};");
  lines.push("");
  return lines.join("\n");
}

function renderAssignments(assignments: Record<string, string>): string {
  const lines: string[] = [];
  lines.push(BANNER);
  lines.push(`// Source: packages/agent-registry/python/axis_agent_registry/assignments.py`);
  lines.push(`// Regenerate with: npm run sync-twin`);
  lines.push(`// Drift check:    npm run sync-twin:check`);
  lines.push("");
  lines.push("export const DEFAULT_ASSIGNMENTS: Record<string, string> = {");
  const sortedRoles = Object.keys(assignments).sort();
  for (const role of sortedRoles) {
    lines.push(`  ${escapeTsString(role)}: ${escapeTsString(assignments[role])},`);
  }
  lines.push("};");
  lines.push("");
  return lines.join("\n");
}

function renderPairs(pairs: Envelope["pairs"]): string {
  // Pretty-print with 2-space indent + trailing newline so editors don't
  // fight the file.
  return JSON.stringify(pairs, null, 2) + "\n";
}

function readIfExists(path: string): string | null {
  if (!existsSync(path)) return null;
  return readFileSync(path, "utf8");
}

function unifiedDiff(label: string, expected: string, actual: string): string {
  // Minimal hand-rolled line diff — keeps zero external deps. Sufficient
  // for human-readable CI output.
  const expLines = expected.split("\n");
  const actLines = actual.split("\n");
  const max = Math.max(expLines.length, actLines.length);
  const out: string[] = [`--- ${label} (expected, freshly generated from Python)`];
  out.push(`+++ ${label} (on disk)`);
  for (let i = 0; i < max; i++) {
    const e = expLines[i];
    const a = actLines[i];
    if (e === a) continue;
    if (e !== undefined) out.push(`-${i + 1}: ${e}`);
    if (a !== undefined) out.push(`+${i + 1}: ${a}`);
  }
  return out.join("\n");
}

function ensureDir(filePath: string): void {
  const dir = dirname(filePath);
  if (!existsSync(dir)) mkdirSync(dir, { recursive: true });
}

function normalise(s: string): string {
  // Normalise CRLF -> LF + trim trailing whitespace per line so editor
  // settings don't break the drift check.
  return s.replace(/\r\n/g, "\n").split("\n").map((l) => l.replace(/[ \t]+$/, "")).join("\n");
}

async function main(): Promise<void> {
  const argv = process.argv.slice(2);
  const checkMode = argv.includes("--check");

  const envelope = loadEnvelope();
  const catalogTs = renderCatalog(envelope.catalog);
  const assignmentsTs = renderAssignments(envelope.assignments);
  const pairsJson = renderPairs(envelope.pairs);

  if (checkMode) {
    const drifts: string[] = [];
    const checks: Array<[string, string, string]> = [
      [CATALOG_OUT, catalogTs, "catalog.ts"],
      [ASSIGNMENTS_OUT, assignmentsTs, "assignments.ts"],
      [PAIRS_OUT, pairsJson, "python-pairs.json"],
    ];
    for (const [path, expected, label] of checks) {
      const actual = readIfExists(path);
      if (actual === null) {
        drifts.push(`MISSING: ${label} not on disk at ${path}`);
        continue;
      }
      if (normalise(actual) !== normalise(expected)) {
        drifts.push(unifiedDiff(label, expected, actual));
      }
    }
    if (drifts.length > 0) {
      console.error("sync-twin: DRIFT DETECTED");
      for (const d of drifts) {
        console.error("");
        console.error(d);
      }
      console.error("");
      console.error("To fix: run `npm run sync-twin` from the repo root.");
      process.exit(1);
    }
    console.log(
      `sync-twin: in sync ` +
        `(catalog=${Object.keys(envelope.catalog).length} entries, ` +
        `assignments=${Object.keys(envelope.assignments).length} roles, ` +
        `pairs=${envelope.pairs.length})`,
    );
    process.exit(0);
  }

  // Write mode
  ensureDir(CATALOG_OUT);
  writeFileSync(CATALOG_OUT, catalogTs, "utf8");
  writeFileSync(ASSIGNMENTS_OUT, assignmentsTs, "utf8");
  ensureDir(PAIRS_OUT);
  writeFileSync(PAIRS_OUT, pairsJson, "utf8");

  console.log(
    `synced ${Object.keys(envelope.catalog).length} catalog entries, ` +
      `${Object.keys(envelope.assignments).length} assignments, ` +
      `${envelope.pairs.length} snapshot pairs`,
  );
}

main().catch((err) => {
  console.error("sync-twin: fatal:", err);
  process.exit(2);
});
